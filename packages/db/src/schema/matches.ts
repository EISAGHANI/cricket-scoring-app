/**
 * Matches and the scoring event log (Phase 3 slice of DATA_MODEL.md, ADR-0005).
 * `ball_events` is append-only: a trigger (migration 0003) rejects UPDATE and DELETE.
 */
import type { MatchRules, MatchState } from "@cricket/scoring-engine";
import { sql } from "drizzle-orm";
import {
	boolean,
	check,
	index,
	integer,
	jsonb,
	pgEnum,
	pgTable,
	primaryKey,
	smallint,
	text,
	timestamp,
	uniqueIndex,
	uuid,
} from "drizzle-orm/pg-core";
import { users } from "./auth";
import { createdAt, id, updatedAt } from "./columns";
import { players, teams, venues } from "./people";

export const matchStatusEnum = pgEnum("match_status", [
	"SCHEDULED",
	"LIVE",
	"COMPLETED",
	"ABANDONED",
	"CANCELLED",
]);

/** What match lists show without replaying the log; rewritten after every accepted event. */
export interface MatchSummary {
	innings: {
		teamId: string;
		runs: number;
		wickets: number;
		/** "12.3", or "45 balls" for The Hundred. */
		overs: string;
		superOver: boolean;
	}[];
	/** "Need 23 from 14 balls", "Lions won by 5 wickets", … */
	status: string | null;
}

export const matches = pgTable(
	"matches",
	{
		id: id(),
		homeTeamId: uuid("home_team_id")
			.notNull()
			.references(() => teams.id, { onDelete: "restrict" }),
		awayTeamId: uuid("away_team_id")
			.notNull()
			.references(() => teams.id, { onDelete: "restrict" }),
		venueId: uuid("venue_id").references(() => venues.id, { onDelete: "set null" }),
		scheduledAt: timestamp("scheduled_at", { withTimezone: true }),
		status: matchStatusEnum("status").notNull().default("SCHEDULED"),
		/** Preset the rules came from (display only; the rules themselves are authoritative). */
		preset: text("preset").notNull(),
		/** MatchRules agreed at setup. MATCH_STARTED must carry exactly these rules. */
		rules: jsonb("rules").$type<MatchRules>().notNull(),
		/** Denormalised head of the event log (0 = nothing recorded). */
		lastSeq: integer("last_seq").notNull().default(0),
		summary: jsonb("summary").$type<MatchSummary>(),
		startedAt: timestamp("started_at", { withTimezone: true }),
		completedAt: timestamp("completed_at", { withTimezone: true }),
		createdBy: uuid("created_by").references(() => users.id, { onDelete: "set null" }),
		createdAt: createdAt(),
		updatedAt: updatedAt(),
	},
	(t) => [
		index("matches_status_idx").on(t.status, t.scheduledAt),
		index("matches_home_idx").on(t.homeTeamId, t.scheduledAt),
		index("matches_away_idx").on(t.awayTeamId, t.scheduledAt),
		index("matches_venue_idx").on(t.venueId),
		check("matches_distinct_teams", sql`${t.homeTeamId} <> ${t.awayTeamId}`),
	],
);

/** Playing XI and substitutes. `name` is the public-safe name at selection (written into events). */
export const matchPlayers = pgTable(
	"match_players",
	{
		matchId: uuid("match_id")
			.notNull()
			.references(() => matches.id, { onDelete: "cascade" }),
		teamId: uuid("team_id")
			.notNull()
			.references(() => teams.id, { onDelete: "restrict" }),
		playerId: uuid("player_id")
			.notNull()
			.references(() => players.id, { onDelete: "restrict" }),
		name: text("name").notNull(),
		/** 0-based order within the team's selection (batting order for the XI). */
		position: smallint("position").notNull(),
		isSubstitute: boolean("is_substitute").notNull().default(false),
		isCaptain: boolean("is_captain").notNull().default(false),
		isKeeper: boolean("is_keeper").notNull().default(false),
	},
	(t) => [
		primaryKey({ columns: [t.matchId, t.playerId] }),
		index("match_players_player_idx").on(t.playerId),
		index("match_players_team_idx").on(t.matchId, t.teamId),
	],
);

export const officialRoleEnum = pgEnum("official_role", [
	"UMPIRE_1",
	"UMPIRE_2",
	"TV_UMPIRE",
	"REFEREE",
]);

/** Umpires and referee. Free-text names in Phase 3; accounts and ratings come in Phase 6. */
export const matchOfficials = pgTable(
	"match_officials",
	{
		id: id(),
		matchId: uuid("match_id")
			.notNull()
			.references(() => matches.id, { onDelete: "cascade" }),
		role: officialRoleEnum("role").notNull(),
		name: text("name").notNull(),
		userId: uuid("user_id").references(() => users.id, { onDelete: "set null" }),
	},
	(t) => [uniqueIndex("match_officials_role_idx").on(t.matchId, t.role)],
);

/**
 * The scoring event log (ADR-0005). `id` is generated by the client (UUIDv7) so retries are
 * idempotent; `(match_id, seq)` is unique and gapless.
 */
export const ballEvents = pgTable(
	"ball_events",
	{
		id: uuid("id").primaryKey(),
		matchId: uuid("match_id")
			.notNull()
			.references(() => matches.id, { onDelete: "restrict" }),
		seq: integer("seq").notNull(),
		/** 1-based innings the event belongs to; null before the first innings. */
		inningsNo: smallint("innings_no"),
		type: text("type").notNull(),
		payload: jsonb("payload").$type<Record<string, unknown>>().notNull(),
		schemaVersion: smallint("schema_version").notNull(),
		engineVersion: text("engine_version").notNull(),
		createdBy: uuid("created_by").references(() => users.id, { onDelete: "set null" }),
		deviceId: text("device_id").notNull(),
		clientTimestamp: timestamp("client_timestamp", { withTimezone: true }).notNull(),
		serverTimestamp: timestamp("server_timestamp", { withTimezone: true }).notNull().defaultNow(),
	},
	(t) => [
		uniqueIndex("ball_events_match_seq_idx").on(t.matchId, t.seq),
		index("ball_events_match_innings_idx").on(t.matchId, t.inningsNo),
		check("ball_events_seq_positive", sql`${t.seq} > 0`),
	],
);

/**
 * Replay cache: the latest state per match, written at ends of overs and innings. Ignored when
 * `engine_version` differs from the running engine (the log is replayed instead).
 */
export const matchStateSnapshots = pgTable("match_state_snapshots", {
	matchId: uuid("match_id")
		.primaryKey()
		.references(() => matches.id, { onDelete: "cascade" }),
	seq: integer("seq").notNull(),
	engineVersion: text("engine_version").notNull(),
	state: jsonb("state").$type<MatchState>().notNull(),
	createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});
